const FILL = ['pause', 'play', 'star'];

// The package doesn't export package.json, so look for it along the module search paths.
const root = require.resolve
  .paths('@phosphor-icons/core')
  .map((dir) => path.join(dir, '@phosphor-icons/core'))
  .find((dir) => fs.existsSync(path.join(dir, 'assets/duotone')));
if (!root) throw new Error('Install @phosphor-icons/core first (see the comment at the top).');

function read(name, weight) {
  const svg = fs.readFileSync(path.join(root, 'assets', weight, `${name}-${weight}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"( opacity="0.2")?\/>/g)];
  if (paths.length === 0) throw new Error(`${name}: no paths found`);
  return {
    duo: paths.filter((p) => p[2]).map((p) => p[1]),
    solid: paths.filter((p) => !p[2]).map((p) => p[1]),
  };
}

const out = {};
for (const name of DUOTONE) out[name] = read(name, 'duotone');
for (const name of FILL) out[`${name}-fill`] = read(name, 'fill');

const target = path.join(__dirname, '../src/components/icons/phosphor-paths.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(
  target,
  `// Generated by scripts/make-icon-data.js from @phosphor-icons/core (MIT,
// https://phosphoricons.com) — do not edit by hand.
// Each icon: \`duo\` = the soft background shape (drawn at 20% opacity), \`solid\` = the outline.

export const PHOSPHOR = ${JSON.stringify(out, null, 2)} as const;

export type IconName = keyof typeof PHOSPHOR;
`,
);
console.log(`wrote ${Object.keys(out).length} icons to ${path.relative(process.cwd(), target)}`);
